$boot = @'
// ---- Weight Loss and Waste O2O as its own page: sign in, then the Waste screen is the whole app ----
document.body.classList.add('waste-app');
const WASTE_HOME_URL='__HUB__';
function wasteHideScreens(){
  ['roleScreen','grHomeScreen','loginScreen','mainApp'].forEach(id=>{ const e=document.getElementById(id); if(e) e.style.display='none'; });
}
function wasteShowLogin(){
  currentRole=null;
  wasteHideScreens();
  document.getElementById('wasteLogOverlay').style.display='none';
  clearInterval(wasteDateTimeTimer);
  document.getElementById('appBar').style.display='none';
  document.getElementById('loginScreen').style.display='flex';
}
function wasteEnter(sess){
  currentRole=sess.role;
  wasteHideScreens();
  document.getElementById('appBar').style.display='flex';
  document.getElementById('appBarUser').textContent=(sess.name||'')+(sess.dept?' · '+sess.dept:'');
  applyEmployeeOnlyVisibility();
  openWasteLog();
}
function showRoleScreen(){ wasteShowLogin(); }                      // log out -> the sign-in card
function closeWasteLog(){ location.href=WASTE_HOME_URL; }           // (the close button of the old pop-up) -> the apps hub
function wasteBoot(){
  const sess=getSession();
  if(sess&&sess.role==='employee') wasteEnter(sess); else wasteShowLogin();
}
wasteBoot();
